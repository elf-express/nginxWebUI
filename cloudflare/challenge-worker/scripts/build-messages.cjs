const fs = require('node:fs');
const path = require('node:path');
const resources = path.resolve(__dirname, '../../../src/main/resources');
const target = path.resolve(__dirname, '../src/messages.generated.js');
const source = { 'zh-CN': 'messages.properties', 'zh-TW': 'messages_zh_TW.properties', en: 'messages_en_US.properties' };
function parseProperties(text) {
  const result = {};
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^((?:challengeStr|challengeWorkerStr)\.[^=\s]+)=(.*)$/);
    if (match) result[match[1]] = match[2].replace(/\\u([a-f0-9]{4})|\\(.)/gi, (_all, hex, char) =>
      hex ? String.fromCharCode(parseInt(hex, 16)) : ({ n: '\n', r: '\r', t: '\t', f: '\f' }[char] ?? char));
  }
  return result;
}
function buildMessages(locales) {
  const keys = [...new Set(Object.values(locales).flatMap(Object.keys))].sort();
  for (const key of ['preview', 'invalidTicket', 'serviceUnavailable', 'retry', 'checkboxLabel'])
    if (!keys.includes('challengeWorkerStr.' + key)) throw new Error('Missing challengeWorkerStr.' + key);
  const result = {};
  for (const locale of Object.keys(source)) {
    result[locale] = {};
    for (const key of keys) {
      if (!locales[locale]?.[key]) throw new Error('Missing ' + locale + ': ' + key);
      result[locale][key] = locales[locale][key];
    }
  }
  return '// Generated by scripts/build-messages.cjs; edit messages*.properties instead.\nexport const messages = ' + JSON.stringify(result, null, 2) + ';\n';
}
if (require.main === module) {
  const locales = Object.fromEntries(Object.entries(source).map(([locale, file]) => [locale, parseProperties(fs.readFileSync(path.join(resources, file), 'latin1'))]));
  const output = buildMessages(locales);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Generated messages differ; run build-messages.cjs');
  } else fs.writeFileSync(target, output, 'utf8');
}
module.exports = { parseProperties, buildMessages };
